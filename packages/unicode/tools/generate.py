#!/usr/bin/env python3
"""Generate fixed-width Unicode tables and complete conformance inputs.

Consumes only checksum-pinned UCD files. No host Unicode database participates.
Run with --download to retrieve missing inputs, or point --data at a local copy.
"""

import argparse
import hashlib
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SPEC = json.loads((ROOT / "tools/data.json").read_text())
GRAPHEME = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
            "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]
WORD = ["Other", "CR", "LF", "Newline", "Extend", "ZWJ", "Format", "Regional_Indicator",
        "WSegSpace", "ALetter", "Hebrew_Letter", "Numeric", "Katakana", "ExtendNumLet",
        "MidLetter", "MidNum", "MidNumLet", "Single_Quote", "Double_Quote"]


def records(data, name):
    for line in data[name].splitlines():
        body = line.partition("#")[0].strip()
        if body and not body.startswith("@"):
            yield [field.strip() for field in body.split(";")]


def interval(value):
    ends = value.split("..")
    return int(ends[0], 16), int(ends[-1], 16)


def packed(values):
    result = []
    for value in values:
        if not 0 <= value < 2**24:
            raise ValueError(f"table value out of range: {value}")
        result.extend(chr(32 + ((value >> shift) & 63)) for shift in (0, 6, 12, 18))
    return "".join(result)


def literal(text):
    return json.dumps(text, ensure_ascii=True)


def table(name, rows):
    flat = [value for row in rows for value in row]
    text = literal(packed(flat))
    return f"internal {name} : Unit -> Bytes\nlet {name} _ =\n  Bytes.fromString {text}\n"


def ranges(data, name, values):
    return sorted((*interval(row[0]), values.index(row[1])) for row in records(data, name))


def text_from_hex(text):
    return "".join(chr(int(cp, 16)) for cp in text.split())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=ROOT / "tools/cache")
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = {}
    for name, checksum in SPEC["sha256"].items():
        path = args.data / name
        if not path.exists() and args.download:
            payload = urllib.request.urlopen(SPEC["baseUrl"] + name, timeout=60).read()
            if hashlib.sha256(payload).hexdigest() != checksum:
                raise ValueError(f"checksum mismatch: {name}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(payload)
        payload = path.read_bytes()
        if hashlib.sha256(payload).hexdigest() != checksum:
            raise ValueError(f"checksum mismatch: {name}")
        data[name] = payload.decode("utf-8")

    preamble = ("module UnicodeTables\n\n"
                "// Generated by tools/generate.py from checksum-pinned Unicode 18.0.0 data.\n"
                "// Four ASCII sextets encode each unsigned 24-bit field, low sextet first.\n")
    source = []
    source.append(table("graphemes", ranges(data, "auxiliary/GraphemeBreakProperty.txt", GRAPHEME)))
    source.append(table("words", ranges(data, "auxiliary/WordBreakProperty.txt", WORD)))
    source.append(table("pictographs", sorted((*interval(row[0]), 1) for row in records(data, "emoji/emoji-data.txt") if row[1] == "Extended_Pictographic")))
    source.append(table("conjuncts", sorted((*interval(row[0]), ["None", "Consonant", "Extend", "Linker"].index(row[2])) for row in records(data, "DerivedCoreProperties.txt") if row[1] == "InCB")))
    source.append(table("whitespace", sorted((*interval(row[0]), 1) for row in records(data, "PropList.txt") if row[1] == "White_Space")))
    ccc, decomps, decomposed, compositions = [], [], [], []
    excluded = set()
    for row in records(data, "DerivedNormalizationProps.txt"):
        if row[1] == "Full_Composition_Exclusion":
            a, b = interval(row[0]); excluded.update(range(a, b + 1))
    for row in records(data, "UnicodeData.txt"):
        cp = int(row[0], 16)
        if int(row[3]):
            ccc.append((cp, cp, int(row[3])))
        if row[5]:
            fields = row[5].split()
            compat = fields[0].startswith("<")
            mapping = [int(field, 16) for field in fields[1 if compat else 0:]]
            decomps.append((cp, int(compat), len(decomposed), len(mapping)))
            decomposed.extend(mapping)
            if not compat and len(mapping) == 2 and cp not in excluded:
                compositions.append((*mapping, cp))
    source.extend([table("combining", ccc), table("decompositions", decomps),
                   table("decomposed", [(cp,) for cp in decomposed]), table("compositions", sorted(compositions))])
    folds, folded = [], []
    for row in records(data, "CaseFolding.txt"):
        if row[1] in ("C", "F"):
            mapping = [int(cp, 16) for cp in row[2].split()]
            folds.append((int(row[0], 16), len(folded), len(mapping)))
            folded.extend(mapping)
    source.extend([table("folds", folds), table("folded", [(cp,) for cp in folded])])
    outputs = {ROOT / "src/UnicodeTables.fai": preamble + "\n".join(source)}
    counts = {}
    for name in ("Grapheme", "Word"):
        lines = []
        for line in data[f"auxiliary/{name}BreakTest.txt"].splitlines():
            body = line.partition("#")[0].strip()
            if not body:
                continue
            position, boundaries, text = 0, [], []
            for item in body.split():
                if item == "÷": boundaries.append(str(position))
                elif item != "×":
                    char = chr(int(item, 16)); text.append(char); position += len(char.encode("utf-8"))
            lines.append(",".join(boundaries) + "\t" + "".join(text).encode("utf-8").hex())
        outputs[ROOT / f"data/{name.lower()}.tsv"] = "\n".join(lines) + "\n"
        counts[name.lower()] = len(lines)
    lines = []
    for row in records(data, "NormalizationTest.txt"):
        lines.append("\t".join(text_from_hex(field).encode("utf-8").hex() for field in row[:5]))
    outputs[ROOT / "data/normalization.tsv"] = "\n".join(lines) + "\n"
    counts["normalization"] = len(lines)
    lines = []
    for row in records(data, "CaseFolding.txt"):
        if row[1] in ("C", "F"):
            lines.append(chr(int(row[0], 16)).encode("utf-8").hex() + "\t" + text_from_hex(row[2]).encode("utf-8").hex())
    outputs[ROOT / "data/folding.tsv"] = "\n".join(lines) + "\n"
    counts["folding"] = len(lines)
    outputs[ROOT / "data/counts.json"] = json.dumps(counts, indent=2, sort_keys=True) + "\n"
    for path, content in outputs.items():
        if args.check:
            if path.read_text() != content:
                raise ValueError(f"generated output differs: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(json.dumps(counts, sort_keys=True))


if __name__ == "__main__":
    main()
